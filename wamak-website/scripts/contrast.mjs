// Generates docs/contrast.md from the token values below (keep in sync with globals.css).
// Usage: node scripts/contrast.mjs
import { writeFileSync } from "node:fs";

const T = {
  "navy-950": "#031738", "navy-900": "#05245C", "navy-800": "#0B3272", "navy-200": "#B9C4D8",
  "leaf-500": "#3C9426", "leaf-700": "#287433", "ivory-50": "#F7F5EE", "ivory-100": "#EFEBE0",
  "jute-300": "#C9A66B", "jute-700": "#7A5A24", "ink-900": "#1B222B", "ink-600": "#4A5360",
  "mist-100": "#E9EEF3", white: "#FFFFFF", field: "#767063", danger: "#B3261E",
};

const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => { const [x, y] = [lum(T[a]), lum(T[b])].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };

// [foreground, background, role, requirement] — requirement: "text" 4.5, "large" 3, "ui" 3
const pairs = [
  ["ink-900", "ivory-50", "Body text", "text"],
  ["ink-900", "white", "Body text on cards / fields", "text"],
  ["ink-900", "mist-100", "Body text on form panels", "text"],
  ["ink-600", "ivory-50", "Secondary text", "text"],
  ["ink-600", "white", "Secondary text on cards, placeholders", "text"],
  ["ink-600", "mist-100", "Hints on form panels", "text"],
  ["ink-900", "ivory-100", "Body text on sunken sections", "text"],
  ["ink-600", "ivory-100", "Secondary text on sunken sections", "text"],
  ["navy-900", "ivory-100", "Headings on sunken sections", "text"],
  ["jute-700", "ivory-100", "Category labels on sunken sections", "text"],
  ["navy-900", "ivory-50", "Headings, secondary button label", "text"],
  ["navy-900", "white", "Headings on cards", "text"],
  ["navy-900", "mist-100", "Headings on form panels", "text"],
  ["navy-900", "jute-300", "Inverse button hover label", "text"],
  ["ivory-50", "navy-900", "Text on navy chapters, primary button", "text"],
  ["ivory-50", "navy-800", "Primary button hover", "text"],
  ["ivory-50", "navy-950", "Footer text", "text"],
  ["navy-200", "navy-900", "Secondary text on navy", "text"],
  ["navy-200", "navy-950", "Secondary text in footer", "text"],
  ["jute-300", "navy-900", "Accent text / rules on navy", "text"],
  ["jute-300", "navy-950", "Accent text in footer", "text"],
  ["leaf-700", "ivory-50", "Links", "text"],
  ["leaf-700", "white", "Links on cards", "text"],
  ["leaf-700", "mist-100", "Links on form panels", "text"],
  ["leaf-700", "ivory-100", "Links on sunken sections", "text"],
  ["jute-700", "ivory-50", "Jute-toned text on light", "text"],
  ["danger", "white", "Error text in fields", "text"],
  ["danger", "mist-100", "Error text on form panels", "text"],
  ["danger", "ivory-50", "Error text on ivory", "text"],
  ["leaf-700", "ivory-50", "Focus ring on light", "ui"],
  ["jute-300", "navy-900", "Focus ring on navy", "ui"],
  ["field", "white", "Form-field border", "ui"],
  ["field", "mist-100", "Form-field border vs panel", "ui"],
  ["leaf-500", "ivory-50", "Fibre thread, logo leaf (graphic)", "ui"],
  ["leaf-500", "navy-900", "Fibre thread on navy (graphic)", "ui"],
  ["jute-300", "ivory-50", "Jute rule on ivory (decorative only)", "decor"],
  ["leaf-500", "white", "leaf-500 as text — NOT ALLOWED", "text"],
  ["leaf-700", "navy-900", "leaf-700 on navy — NOT ALLOWED", "ui"],
];

const need = { text: 4.5, large: 3, ui: 3, decor: 0 };
const rows = pairs.map(([fg, bg, role, req]) => {
  const r = ratio(fg, bg);
  const pass = req === "decor" ? "Decorative (exempt)" : r >= need[req] ? "Pass" : "**Fail — do not use**";
  return `| \`${fg}\` ${T[fg]} | \`${bg}\` ${T[bg]} | ${role} | ${r.toFixed(2)}:1 | ${req === "text" ? "4.5:1" : req === "decor" ? "—" : "3:1"} | ${pass} |`;
});

writeFileSync("docs/contrast.md", `# Contrast audit (WCAG 2.2 AA)

Generated by \`node scripts/contrast.mjs\`. Re-run whenever a token changes.
Brand values are provisional (sampled from the PNG logo) and must be re-checked when the vector master arrives.

| Foreground | Background | Role | Ratio | Needs | Result |
|---|---|---|---|---|---|
${rows.join("\n")}

## Rules that follow from this

- \`leaf-500\` is for graphics only (thread, logo leaf, icons ≥ 24px). Never text.
- \`leaf-700\` carries links and the focus ring on light surfaces only. On navy, the focus ring switches to \`jute-300\` (handled in \`globals.css\`).
- \`jute-300\` never carries text on ivory or white; use \`jute-700\` for jute-toned text on light.
- Form-field borders use \`field\` (not \`line\`), because a field boundary must reach 3:1 (WCAG 1.4.11).
- \`line\` is purely decorative (hairlines between content that is already separated by space or headings).
`);
