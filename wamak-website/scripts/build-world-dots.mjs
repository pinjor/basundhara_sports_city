// Generates src/content/generated/world.ts: a dotted world map as ONE compact
// SVG path (round-capped zero-length segments), plus projected anchor points.
// Run: node scripts/build-world-dots.mjs   (dotted-map is a devDependency only)
import { writeFileSync } from "node:fs";
import DottedMapModule from "dotted-map";

const DottedMap = DottedMapModule.default ?? DottedMapModule;
const map = new DottedMap({ height: 64, grid: "diagonal" });

const anchors = {
  bangladesh: { lat: 23.81, lng: 90.41 },
  northAmerica: { lat: 40, lng: -98 },
  europe: { lat: 50, lng: 10 },
  middleEast: { lat: 24.5, lng: 46 },
  asia: { lat: 36, lng: 128 },
  africa: { lat: 2, lng: 22 },
};

const points = map.getPoints();
const width = Math.max(...points.map((p) => p.x)) + 1;
const maxY = Math.max(...points.map((p) => p.y));
// Drop Antarctica (bottom band) — it adds weight and no meaning here.
const cutoff = maxY * 0.9;
const kept = points.filter((p) => p.y < cutoff);
const height = Math.ceil(cutoff) + 1;
const r = (n) => Math.round(n * 100) / 100;
const d = kept.map((p) => `M${r(p.x)} ${r(p.y)}h0`).join("");

const pins = Object.fromEntries(
  Object.entries(anchors).map(([k, v]) => {
    const p = map.getPin(v);
    return [k, { x: r(p.x), y: r(p.y) }];
  }),
);

writeFileSync(
  "src/content/generated/world.ts",
  `// Generated by scripts/build-world-dots.mjs — do not edit by hand.\n` +
    `export const world = ${JSON.stringify({ width, height, dots: kept.length, pins, d })} as const;\n`,
);
console.log(`world.ts: ${kept.length} dots, ${width}×${height}, ${(d.length / 1024).toFixed(1)} KB path`);
